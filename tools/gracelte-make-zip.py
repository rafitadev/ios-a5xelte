#!/usr/bin/env python3
"""Build a TWRP-flashable zip that writes a BOOT image on a Galaxy Note7 (gracelte).

Two ways to call it:
  --image xnu-boot6.img                 zip an image you already packed
  --stock boot-stock.img --loader xnu_boot.Image --payload payload-4-fast.bin
                                        pack it with gracelte-pack-boot.py first

The zip only writes the BOOT partition. It checks the device (refuses an
N935F/gracerlte or other models), that the image fits, the md5 of the image
before and after writing, and saves the BOOT it replaces to
/sdcard/ios-note7/boot-before-last.img when storage is writable.
"""
import argparse
import hashlib
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

SCRIPT = r'''#!/sbin/sh
# Galaxy Note7 (gracelte) BOOT installer, generated by tools/gracelte-make-zip.py
OUTFD=$2
ZIP=$3
BOOT_DEV="${GRACELTE_TEST_BOOT:-/dev/block/platform/155a0000.ufs/by-name/BOOT}"
EXPECT_SIZE=@PARTSIZE@
IMG_SIZE=@IMGSIZE@
IMG_MD5=@MD5@
WORK=/tmp/gracelte-zip

ui_print() { printf 'ui_print %s\nui_print\n' "$1" >> /proc/self/fd/$OUTFD; }
abort() { ui_print "ABORTED: $1"; ui_print "Nothing was written."; exit 1; }

ui_print "@NAME@"
ui_print "Galaxy Note7 (N930F) BOOT installer"

dev=$(getprop ro.product.device 2>/dev/null)
model=$(getprop ro.product.model 2>/dev/null)
bl=$(getprop ro.bootloader 2>/dev/null)
id="$dev $model $bl"

[ -e "$BOOT_DEV" ] || abort "BOOT partition not found at $BOOT_DEV"
dev_size=$(blockdev --getsize64 "$BOOT_DEV" 2>/dev/null)
[ -n "$dev_size" ] || dev_size=$(wc -c < "$BOOT_DEV")

@DEVCHECK@

[ "$dev_size" -ge "$IMG_SIZE" ] || abort "image ($IMG_SIZE bytes) is larger than BOOT ($dev_size bytes)"

rm -rf "$WORK"; mkdir -p "$WORK" || abort "cannot create $WORK"
unzip -o "$ZIP" boot.img -d "$WORK" >/dev/null 2>&1 || abort "cannot unzip boot.img"
[ "$(wc -c < "$WORK/boot.img")" = "$IMG_SIZE" ] || abort "boot.img has the wrong size"
[ "$(md5sum "$WORK/boot.img" | cut -d' ' -f1)" = "$IMG_MD5" ] || abort "boot.img md5 does not match the zip"
ui_print "Image checked (md5 $IMG_MD5)"

if mkdir -p /sdcard/ios-note7 2>/dev/null && [ -w /sdcard/ios-note7 ]; then
    dd if="$BOOT_DEV" of=/sdcard/ios-note7/boot-before-last.img bs=1048576 2>/dev/null \
        && ui_print "Saved the current BOOT to /sdcard/ios-note7/boot-before-last.img" \
        || ui_print "warning: could not save the current BOOT"
else
    ui_print "warning: /sdcard not writable, current BOOT not saved (keep your boot-stock.img!)"
fi

try=1
while [ "$try" -le 2 ]; do
    dd if="$WORK/boot.img" of="$BOOT_DEV" bs=1048576 conv=fsync,notrunc 2>/dev/null
    back=$(head -c "$IMG_SIZE" "$BOOT_DEV" | md5sum | cut -d' ' -f1)
    if [ "$back" = "$IMG_MD5" ]; then
        ui_print "BOOT written and verified (md5 $back)"
        rm -rf "$WORK"
        ui_print "Done. Reboot from TWRP."
        exit 0
    fi
    ui_print "verify failed (try $try), md5 $back"
    try=$((try + 1))
done
ui_print "ERROR: BOOT does not match after 2 writes. DO NOT REBOOT. Flash your boot-stock.img."
exit 1
'''

DEVCHECK = r'''case "$id" in
    *gracerlte*|*N935*) abort "this is a Note FE (N935F, gracerlte), not a Note7 (N930F)" ;;
    *gracelte*|*N930*) ui_print "Device: $dev $model" ;;
    *)
        if [ -z "$(echo "$id" | tr -d ' ')" ] && [ "$dev_size" = "$EXPECT_SIZE" ]; then
            ui_print "warning: TWRP reports no device props; BOOT size matches"
        else
            abort "device is \"$id\", expected gracelte / SM-N930F"
        fi ;;
esac'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--image', type=Path)
    ap.add_argument('--stock', type=Path)
    ap.add_argument('--loader', type=Path)
    ap.add_argument('--payload', type=Path)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--name', default='iOS on Galaxy Note7')
    ap.add_argument('--partition-size', type=int, default=41943040)
    ap.add_argument('--no-device-check', action='store_true',
                    help='skip the gracelte/N930 check (still checks that the image fits)')
    a = ap.parse_args()

    tmp = None
    image = a.image
    if a.stock or a.loader or a.payload:
        if not (a.stock and a.loader and a.payload) or image:
            ap.error('use either --image, or all of --stock --loader --payload')
        tmp = tempfile.TemporaryDirectory()
        image = Path(tmp.name) / 'boot.img'
        packer = Path(__file__).with_name('gracelte-pack-boot.py')
        subprocess.run([sys.executable, str(packer), 'pack', str(a.stock), str(a.loader), str(image),
                        '--append', str(a.payload), '--partition-size', str(a.partition_size)], check=True)
    if not image:
        ap.error('give --image, or --stock --loader --payload')

    data = Path(image).read_bytes()
    if len(data) > a.partition_size:
        sys.exit(f'image is {len(data)} bytes, larger than --partition-size {a.partition_size}')
    md5 = hashlib.md5(data).hexdigest()
    devcheck = 'ui_print "warning: device check disabled"' if a.no_device_check else DEVCHECK
    name = a.name.replace('"', "'").replace('\\', '/')
    script = (SCRIPT.replace('@DEVCHECK@', devcheck).replace('@PARTSIZE@', str(a.partition_size))
              .replace('@IMGSIZE@', str(len(data))).replace('@MD5@', md5).replace('@NAME@', name))
    updater = '# Dummy file; update-binary is a shell script (see tools/gracelte-make-zip.py).\n'

    a.out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(a.out, 'w', zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for arc, content, mode in (('META-INF/com/google/android/update-binary', script, 0o755),
                                   ('META-INF/com/google/android/updater-script', updater, 0o644)):
            zi = zipfile.ZipInfo(arc, (2026, 1, 1, 0, 0, 0))
            zi.external_attr = mode << 16
            z.writestr(zi, content, zipfile.ZIP_DEFLATED)
        zi = zipfile.ZipInfo('boot.img', (2026, 1, 1, 0, 0, 0))
        zi.external_attr = 0o644 << 16
        z.writestr(zi, data, zipfile.ZIP_DEFLATED)
    print(f'{a.out}: {a.out.stat().st_size} bytes, boot.img {len(data)} bytes md5 {md5}')


if __name__ == '__main__':
    main()
